const std::size_t GLYPH_COUNT = sizeof(GLYPHS) / sizeof(GLYPHS[0]);

std::u32string chars(std::string_view s) {
    std::u32string out;
    std::size_t i = 0;
    while (i < s.size()) {
        const auto b = static_cast<unsigned char>(s[i]);
        std::size_t len = 1;
        char32_t c = b;
        if (b >= 0xf0 && b < 0xf8) {
            len = 4;
            c = b & 0x07;
        } else if (b >= 0xe0) {
            len = 3;
            c = b & 0x0f;
        } else if (b >= 0xc0) {
            len = 2;
            c = b & 0x1f;
        } else if (b >= 0x80) {
            out.push_back(0xfffd);
            i++;
            continue;
        }
        if (i + len > s.size()) {
            out.push_back(0xfffd);
            break;
        }
        for (std::size_t k = 1; k < len; k++) {
            c = (c << 6) | (static_cast<unsigned char>(s[i + k]) & 0x3f);
        }
        out.push_back(c);
        i += len;
    }
    return out;
}

