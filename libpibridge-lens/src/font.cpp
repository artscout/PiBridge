namespace {

const char* const BOX[7] = {"#####", "#...#", "#...#", "#...#", "#...#", "#...#", "#####"};

const char* const* rows(char32_t c) {
    if (c >= 'a' && c <= 'z') {
        c = c - 'a' + 'A';
    }
    for (std::size_t i = 0; i < detail::GLYPH_COUNT; i++) {
        if (detail::GLYPHS[i].c == c) {
            return detail::GLYPHS[i].rows;
        }
    }
    return BOX;
}

} // namespace

bool pixel(char32_t c, std::uint32_t col, std::uint32_t row) {
    if (col >= GLYPH_W || row >= GLYPH_H) {
        return false;
    }
    return rows(c)[row][col] == '#';
}

std::pair<std::uint32_t, std::uint32_t> text_size(std::string_view text, std::uint32_t scale) {
    const auto n = static_cast<std::uint32_t>(detail::chars(text).size());
    if (n == 0) {
        return {0, 0};
    }
    return {(n * (GLYPH_W + 1) - 1) * scale, GLYPH_H * scale};
}

void draw_text(std::string_view text, std::int32_t x0, std::int32_t y0, std::uint32_t scale,
               const std::function<void(std::int32_t, std::int32_t)>& plot) {
    const auto s = static_cast<std::int32_t>(scale);
    const std::u32string cs = detail::chars(text);
    for (std::size_t i = 0; i < cs.size(); i++) {
        const std::int32_t gx = x0 + static_cast<std::int32_t>(i) * (static_cast<std::int32_t>(GLYPH_W) + 1) * s;
        for (std::uint32_t row = 0; row < GLYPH_H; row++) {
            for (std::uint32_t col = 0; col < GLYPH_W; col++) {
                if (pixel(cs[i], col, row)) {
                    for (std::int32_t dy = 0; dy < s; dy++) {
                        for (std::int32_t dx = 0; dx < s; dx++) {
                            plot(gx + static_cast<std::int32_t>(col) * s + dx,
                                 y0 + static_cast<std::int32_t>(row) * s + dy);
                        }
                    }
                }
            }
        }
    }
}

