const std::array<unsigned char, 7>& glyph(char c) {
    const auto& g = glyphs();
    const char u = static_cast<char>(std::toupper(static_cast<unsigned char>(c)));
    const auto it = g.find(u);
    return it != g.end() ? it->second : g.at('?');
}

int textWidth(std::string_view s) { return s.empty() ? 0 : static_cast<int>(s.size()) * 6 - 1; }

void drawText(Batch& b, std::string_view s, Vec3 origin, Vec3 right, Vec3 up, double px, Rgba col) {
    int x = 0;
    for (const char ch : s) {
        const auto& g = glyph(ch);
        for (int row = 0; row < 7; row++) {
            for (int c = 0; c < 5; c++) {
                if ((g[static_cast<std::size_t>(row)] & (1 << (4 - c))) == 0) {
                    continue;
                }
                const Vec3 p = origin + right * ((x + c) * px) + up * ((6 - row) * px);
                b.quad(p, p + right * px, p + right * px + up * px, p + up * px, col);
            }
        }
        x += 6;
    }
}

void drawTextCentered(Batch& b, std::string_view s, Vec3 center, Vec3 right, Vec3 up, double px, Rgba col) {
    const double w = textWidth(s) * px;
    drawText(b, s, center - right * (w / 2) - up * (3.5 * px), right, up, px, col);
}

std::vector<std::string> wrapText(std::string_view s, std::size_t width) {
    std::vector<std::string> lines;
    std::string line;
    std::istringstream in{std::string(s)};
    std::string w;
    while (in >> w) {
        for (char& c : w) {
            c = static_cast<char>(std::toupper(static_cast<unsigned char>(c)));
        }
        if (!line.empty() && line.size() + 1 + w.size() > width) {
            lines.push_back(line);
            line = w;
            continue;
        }
        if (!line.empty()) {
            line += ' ';
        }
        line += w;
    }
    if (!line.empty()) {
        lines.push_back(line);
    }
    return lines;
}

